WILSON_Z = 1.959963984540054  # two-sided 95%

# Identical across every snapshot, or the comparison is refused.
SHARED_PROVENANCE_KEYS = (
    "schema_version", "dataset", "split_namespace", "split_manifest_hash", "source_split",
    "recipes_csv_sha256", "recipes_manifest_sha256", "generation_config_sha256", "geometry_sha256",
    "code_identity_sha256", "lora_train_image_ids_sha256",
)
# Pairwise different across snapshots: the one thing that is allowed to vary.
DISTINCT_PROVENANCE_KEYS = ("lora_weights_dir", "lora_checkpoint_sha256")
# Identical for the same recipe in every snapshot.
PER_RECIPE_KEYS = ("dx", "class_index", "seed", "prompt", "intended_label_vector", "context_image_id")


class ComparisonRefused(SystemExit):
    """A fairness or provenance condition does not hold. Nothing is written."""


# ------------------------------------------------------------------------------------------
# Loading
