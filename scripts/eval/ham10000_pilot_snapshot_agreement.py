# Metrics
# ------------------------------------------------------------------------------------------

def wilson_interval(k: int, n: int, z: float = WILSON_Z) -> tuple[float, float]:
    if n <= 0:
        return (float("nan"), float("nan"))
    p = k / n
    denominator = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denominator
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denominator
    return (max(0.0, centre - half), min(1.0, centre + half))


def prediction_table(pilots: dict[str, dict], probabilities: dict[str, np.ndarray], order: dict[str, list[str]]) -> pd.DataFrame:
    """One row per (snapshot, image): intended class, argmax, every class probability."""
    rows = []
    for name, ids in order.items():
        probs = np.asarray(probabilities[name], dtype=np.float64)
        if probs.shape != (len(ids), len(CLASSIFIER_TARGET_LABELS)):
            raise ComparisonRefused(f"{name}: probability matrix {probs.shape} does not match {len(ids)} images")
        for image_id, p in zip(ids, probs):
            row = pilots[name]["by_id"][image_id]
            intended = int(row["class_index"])
            predicted = int(np.argmax(p))
            rows.append({
                "snapshot": name, "image_id": image_id, "dx": row["dx"], "seed": int(row["seed"]),
                "predicted": CLASSIFIER_TARGET_LABELS[predicted], "p_intended": float(p[intended]),
                "correct": predicted == intended,
                **{f"p_{label}": float(p[i]) for i, label in enumerate(CLASSIFIER_TARGET_LABELS)},
            })
    return pd.DataFrame(rows)


def agreement_table(predictions: pd.DataFrame, snapshots: list[str]) -> pd.DataFrame:
    rows = []
    for name in snapshots:
        part = predictions[predictions["snapshot"] == name]
        for label in CLASSIFIER_TARGET_LABELS:
            cell = part[part["dx"] == label]
            k, n = int(cell["correct"].sum()), int(len(cell))
            low, high = wilson_interval(k, n)
            rows.append({"snapshot": name, "class": label, "k": k, "n": n, "agreement": k / n if n else float("nan"),
                         "wilson_low": low, "wilson_high": high,
                         "mean_intended_probability": float(cell["p_intended"].mean()) if n else float("nan")})
        k, n = int(part["correct"].sum()), int(len(part))
        low, high = wilson_interval(k, n)
        rows.append({"snapshot": name, "class": "ALL", "k": k, "n": n, "agreement": k / n if n else float("nan"),
                     "wilson_low": low, "wilson_high": high, "mean_intended_probability": float(part["p_intended"].mean()) if n else float("nan")})
    return pd.DataFrame(rows)


def confusion_by_snapshot(predictions: pd.DataFrame, snapshots: list[str]) -> dict:
    index = {label: i for i, label in enumerate(CLASSIFIER_TARGET_LABELS)}
    out = {}
    for name in snapshots:
        part = predictions[predictions["snapshot"] == name]
        matrix = confusion_matrix(part["dx"].map(index).to_numpy(), part["predicted"].map(index).to_numpy(), len(CLASSIFIER_TARGET_LABELS))
        out[name] = {"rows_true_cols_predicted": np.asarray(matrix).tolist(), "labels": list(CLASSIFIER_TARGET_LABELS)}
    return out


def paired_flips(predictions: pd.DataFrame, snapshots: list[str]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Per recipe: the verdict in every snapshot. Per snapshot pair: how many recipes flipped each way."""
    wide = predictions.pivot(index="image_id", columns="snapshot", values="correct")[snapshots].astype(bool)
    predicted = predictions.pivot(index="image_id", columns="snapshot", values="predicted")[snapshots]
    dx = predictions.drop_duplicates("image_id").set_index("image_id")["dx"]
    per_recipe = pd.DataFrame({"image_id": wide.index, "dx": dx.reindex(wide.index).to_numpy()})
    for name in snapshots:
        per_recipe[f"correct_{name}"] = wide[name].to_numpy()
        per_recipe[f"predicted_{name}"] = predicted[name].to_numpy()
    per_recipe["verdict_changes"] = wide.nunique(axis=1).gt(1).to_numpy()
    pairs = []
    for i, a in enumerate(snapshots):
        for b in snapshots[i + 1:]:
            pairs.append({"a": a, "b": b,
                          "both_correct": int((wide[a] & wide[b]).sum()),
                          "only_a_correct": int((wide[a] & ~wide[b]).sum()),
                          "only_b_correct": int((~wide[a] & wide[b]).sum()),
                          "both_wrong": int((~wide[a] & ~wide[b]).sum())})
    return per_recipe.reset_index(drop=True), pd.DataFrame(pairs)


def recall_table(val_metrics: dict) -> dict:
    return {label: {"recall": val_metrics["per_class"][label]["recall"], "support": val_metrics["per_class"][label]["support"]}
            for label in CLASSIFIER_TARGET_LABELS} | {"balanced_accuracy": val_metrics["balanced_accuracy"], "macro_f1": val_metrics["macro_f1"]}


