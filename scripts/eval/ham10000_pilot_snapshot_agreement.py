def check_fairness(pilots: dict[str, dict], current_code_identity: str | None) -> dict:
    """Every condition under which the snapshots may be compared. Raises ComparisonRefused on any failure."""
    failures: list[str] = []
    checks: dict[str, object] = {}
    names = list(pilots)
    if len(names) < 2:
        raise ComparisonRefused("need at least two snapshots to compare")

    for name, pilot in pilots.items():
        approval = pilot["approval"]
        if not approval.get("pilot_completed", False):
            failures.append(f"{name}: pilot did not complete")
        if not approval.get("checks", {}).get("passed", False):
            failures.append(f"{name}: pilot automatic checks did not pass")
        by_id: dict[str, dict] = {}
        for row in pilot["rows"]:
            image_id = str(row.get("image_id", ""))
            if image_id in by_id:
                failures.append(f"{name}: duplicate image_id {image_id}")
            by_id[image_id] = row
            if row.get("status") != "accepted":
                failures.append(f"{name}: {image_id} has status {row.get('status')!r}, not 'accepted'")
            if not row.get("image_path") or not Path(str(row["image_path"])).is_file():
                failures.append(f"{name}: {image_id} standardised image missing")
            if CLASSIFIER_TARGET_LABELS[int(row.get("class_index", -1))] != row.get("dx"):
                failures.append(f"{name}: {image_id} dx/class_index inconsistent")
            for key, value in pilot["provenance"].items():
                if row.get(key) != value:
                    failures.append(f"{name}: {image_id} provenance {key} differs from its pilot record")
                    break
        pilot["by_id"] = by_id

    reference = names[0]
    ids = {name: set(pilots[name]["by_id"]) for name in names}
    same_ids = all(ids[name] == ids[reference] for name in names)
    checks["same_recipe_ids"] = same_ids
    checks["n_recipes"] = len(ids[reference])
    if not same_ids:
        failures.append("snapshots do not contain the same recipe ids: " + json.dumps({n: len(v) for n, v in ids.items()}))
    else:
        for image_id in sorted(ids[reference]):
            for key in PER_RECIPE_KEYS:
                values = {json.dumps(pilots[n]["by_id"][image_id].get(key), sort_keys=True) for n in names}
                if len(values) != 1:
                    failures.append(f"{image_id}: {key} differs across snapshots")
        checks["per_recipe_identical"] = list(PER_RECIPE_KEYS)

    shared = {}
    for key in SHARED_PROVENANCE_KEYS:
        values = {n: pilots[n]["provenance"].get(key) for n in names}
        shared[key] = len({json.dumps(v) for v in values.values()}) == 1 and values[reference] is not None
        if not shared[key]:
            failures.append(f"provenance {key} differs or is missing across snapshots: {values}")
    checks["shared_provenance"] = shared

    distinct = {}
    for key in DISTINCT_PROVENANCE_KEYS:
        values = [pilots[n]["provenance"].get(key) for n in names]
        distinct[key] = len(set(values)) == len(values) and None not in values
        if not distinct[key]:
            failures.append(f"provenance {key} must differ between every pair of snapshots: {values}")
    checks["distinct_lora"] = distinct

    if current_code_identity is not None:
        matches = pilots[reference]["provenance"].get("code_identity_sha256") == current_code_identity
        checks["pilots_generated_by_current_source_tree"] = matches
        if not matches:
            failures.append("the pilots were generated by a different source tree than the one running now")

    checks["snapshots"] = {
        name: {
            "stage2_root": pilots[name]["root"],
            "lora_weights_dir": pilots[name]["provenance"].get("lora_weights_dir"),
            "lora_checkpoint_sha256": pilots[name]["provenance"].get("lora_checkpoint_sha256"),
            "lora_step": pilots[name]["provenance"].get("lora_step"),
            "ema_applied": lora_metadata(pilots[name]).get("ema_applied"),
            "pilot_checks": pilots[name]["approval"].get("checks"),
            "pilot_approved_in_this_root": bool(pilots[name]["approval"].get("approval", {}).get("approved", False)),
        }
        for name in names
    }
    checks["failures"] = failures
    checks["passed"] = not failures
    if failures:
        raise ComparisonRefused("snapshot comparison refused:\n  " + "\n  ".join(failures[:25]))
    return checks


def check_classifier_reproduces_itself(recorded: dict, remeasured: dict) -> dict:
    """The model evaluated here must be the model whose classifier_val metrics were recorded."""
    same = recorded.get("confusion_matrix") == remeasured.get("confusion_matrix")
    result = {"recorded_confusion_matrix": recorded.get("confusion_matrix"), "remeasured_confusion_matrix": remeasured.get("confusion_matrix"), "identical": same}
    if not same:
        raise ComparisonRefused("re-measuring the auxiliary classifier on classifier_val does not reproduce selection_metrics.json; "
                                "the loaded model is not the measured one")
    return result


