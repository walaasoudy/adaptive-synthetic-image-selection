#!/usr/bin/env python3
"""Compare Stage 1 LoRA snapshots by how a real-only classifier reads their 35-image pilots.

WHY THIS EXISTS
  After Stage 1 the gen_val loss stopped discriminating between snapshots (flat from step ~2000), and
  the final pilot showed mel / bkl / akiec / df looking alike. `configs/ham10000_stage1.yaml` says the
  step is chosen from gen_val loss AND pilot samples, so this script turns the pilot samples into
  numbers a person can read next to the images. It measures; it does not choose. There is no
  threshold and no selection rule in this file — the snapshot is a human decision.

WHAT IS COMPARED
  One pilot per snapshot, each generated by ham10000_generate_synthetic_images.py --mode pilot into
  its own `paths.stage2_root`, from a byte-identical copy of the same recipes. The intended set is
  step_2000, step_4000, step_8000 (the raw adapter weights, `ema_applied: False`) and final (the EMA
  weights at step 8000, `ema_applied: True`): the three raw snapshots isolate training length, and
  step_8000 vs final isolates the EMA. Comparing raw step_2000 against EMA final directly would vary
  two things at once.

THE COMPARISON IS REFUSED, NOT WARNED ABOUT, UNLESS
  * every snapshot's pilot completed, passed its automatic checks, and has exactly the same recipe
    ids, seeds, prompts and intended labels;
  * recipes, generation config, geometry, split and source tree are identical across snapshots, and
    the source tree is the one running now (so every pilot was generated by this code);
  * every snapshot came from the same Stage 1 training run, and no two snapshots share a LoRA;
  * the classifier is the one auxiliary checkpoint (loaded once, identity checked by
    cam_model_identity), and re-measuring it on classifier_val reproduces its own recorded
    confusion matrix — so the recall printed next to the synthetic numbers belongs to this model.

METRICS, per snapshot s and intended class c (5 images each in a pilot)
  agreement               k/5 images whose argmax is c, with a Wilson 95% interval
  mean_intended_probability  mean softmax p[c] over the same images (continuous; separates snapshots
                          that tie on k)
  classifier_val recall   the classifier's recall for c on REAL classifier_val images, so a low
                          synthetic agreement can be read against how well the classifier knows c
  Also: per-image probabilities, confusion by snapshot, and paired flips (the same recipe and seed
  across snapshots — where the verdict changes).

The pilot recipes are the first five recipes of each class, so these 35 recipe ids are also part of
the full candidate set. They are kept here, and that overlap is recorded in the report.

Reads no held-out split. Writes only under --out-dir, which must be new or empty.

Usage:
    python scripts/eval/ham10000_pilot_snapshot_agreement.py --namespace ham-stratified-v1 \
        --snapshot step_2000=outputs/ham10000/stage2_snapshot_cmp/step_2000 \
        --snapshot step_4000=outputs/ham10000/stage2_snapshot_cmp/step_4000 \
        --snapshot step_8000=outputs/ham10000/stage2_snapshot_cmp/step_8000 \
        --snapshot final=outputs/ham10000/stage2_snapshot_cmp/final \
        --out-dir outputs/ham10000/stage2_snapshot_cmp/evaluation
"""

