def _cell(row) -> str:
    return f"{row.k}/{row.n} [{row.wilson_low:.2f}–{row.wilson_high:.2f}]"


def render_report(agreement: pd.DataFrame, recall: dict, snapshots: list[str], checks: dict, pairs: pd.DataFrame, overlap_note: str) -> str:
    labels = list(CLASSIFIER_TARGET_LABELS)
    ema = {n: checks["snapshots"][n]["ema_applied"] for n in snapshots}
    lines = ["# Pilot snapshot agreement", "",
             "Measures only. No threshold and no selection rule is applied here; the snapshot is chosen by a person.", "",
             "## Agreement: k/5 images the classifier assigns to the intended class [Wilson 95% CI]", "",
             "| snapshot | EMA | " + " | ".join(labels) + " | all 35 |", "|---" * (len(labels) + 3) + "|"]
    for name in snapshots:
        part = agreement[agreement["snapshot"] == name].set_index("class")
        lines.append(f"| {name} | {ema[name]} | " + " | ".join(_cell(part.loc[l]) for l in labels) + f" | {_cell(part.loc['ALL'])} |")
    lines.append("| *classifier_val recall (real)* | — | " + " | ".join(f"{recall[l]['recall']:.2f} (n={recall[l]['support']})" for l in labels)
                 + f" | bal.acc {recall['balanced_accuracy']:.3f} |")
    lines += ["", "## Mean softmax probability of the intended class", "",
              "| snapshot | " + " | ".join(labels) + " | all 35 |", "|---" * (len(labels) + 2) + "|"]
    for name in snapshots:
        part = agreement[agreement["snapshot"] == name].set_index("class")
        lines.append(f"| {name} | " + " | ".join(f"{part.loc[l].mean_intended_probability:.3f}" for l in labels) + f" | {part.loc['ALL'].mean_intended_probability:.3f} |")
    lines += ["", "## Paired flips (same recipe, same seed)", "", "| a | b | both correct | only a | only b | both wrong |", "|---|---|---|---|---|---|"]
    for row in pairs.itertuples():
        lines.append(f"| {row.a} | {row.b} | {row.both_correct} | {row.only_a_correct} | {row.only_b_correct} | {row.both_wrong} |")
    lines += ["", "## Notes", "",
              f"- Fairness check passed: {checks['passed']} (see fairness_check.json).",
              "- step_* snapshots are raw adapter weights; final is the EMA of the same run at step 8000. "
              "Differences between raw snapshots reflect training length for raw weights only.",
              "- 5 images per cell: intervals are wide; read k/5 together with the mean probability and the images.",
              "- The classifier is real-only (classifier_train) and is also Stage 3's scorer; choosing a snapshot with it "
              "mildly favours a generator it agrees with.",
              f"- {overlap_note}", ""]
    return "\n".join(lines)


def build_review_sheet(pilots: dict[str, dict], predictions: pd.DataFrame, snapshots: list[str], out_path: Path, tile=(224, 168)) -> None:
    """Per class: one row per snapshot, the same five recipes in the same columns, verdict on each tile."""
    from PIL import Image, ImageDraw, ImageFont

    try:
        font = ImageFont.load_default(size=14)
        big = ImageFont.load_default(size=20)
    except TypeError:  # Pillow < 10.1
        font = big = ImageFont.load_default()
    width, height = tile
    label_w, caption_h, gap, header_h = 180, 18, 4, 30
    by_key = predictions.set_index(["snapshot", "image_id"])
    ids_by_class = {label: sorted(i for i in pilots[snapshots[0]]["by_id"] if pilots[snapshots[0]]["by_id"][i]["dx"] == label)
                    for label in CLASSIFIER_TARGET_LABELS}
    columns = max(len(v) for v in ids_by_class.values())
    block_h = header_h + len(snapshots) * (height + caption_h + gap)
    sheet = Image.new("RGB", (label_w + columns * (width + gap), block_h * len(CLASSIFIER_TARGET_LABELS)), "white")
    draw = ImageDraw.Draw(sheet)
    for b, label in enumerate(CLASSIFIER_TARGET_LABELS):
        top = b * block_h
        draw.text((8, top + 6), f"intended: {label}", fill="black", font=big)
        for c, image_id in enumerate(ids_by_class[label]):
            draw.text((label_w + c * (width + gap), top + 10), image_id, fill="gray", font=font)
        for r, name in enumerate(snapshots):
            y = top + header_h + r * (height + caption_h + gap)
            draw.text((8, y + height // 2 - 8), name, fill="black", font=font)
            for c, image_id in enumerate(ids_by_class[label]):
                row = pilots[name]["by_id"][image_id]
                raw = Path(str(row.get("raw_image_path") or row["image_path"]))
                with Image.open(raw if raw.is_file() else row["image_path"]) as image:
                    thumb = image.convert("RGB").resize((width, height))
                x = label_w + c * (width + gap)
                sheet.paste(thumb, (x, y))
                verdict = by_key.loc[(name, image_id)]
                colour = (0, 150, 0) if verdict["correct"] else (200, 0, 0)
                draw.rectangle([x, y, x + width - 1, y + height - 1], outline=colour, width=4)
                draw.text((x + 2, y + height + 1), f"-> {verdict['predicted']}  p({label})={verdict['p_intended']:.2f}", fill=colour, font=font)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out_path, quality=90)


