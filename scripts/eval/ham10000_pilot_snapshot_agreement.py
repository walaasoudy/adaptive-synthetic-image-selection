class AuxiliaryPredictor:
    """The one frozen auxiliary checkpoint: loaded once, used for every snapshot and for classifier_val."""

    def __init__(self, namespace: str, device: str | None = None):
        from scripts.asism.ham10000_00_build_cam_reference import load_cam_model
        from scripts.utils.config import load_named_config

        stage1 = load_named_config("ham10000_stage1.yaml", "ham_stage1")
        stage3 = load_named_config("ham10000_stage3.yaml", "ham_stage3")
        splits = load_named_config("splits_ham10000.yaml", "ham_splits")
        self.checkpoint_dir = Path(stage3.auxiliary_classifier.checkpoint_dir) / namespace
        self.model, self.resolution, self.identity, self.manifest = load_cam_model(Path(stage3.auxiliary_classifier.checkpoint_dir), namespace)
        self.device = device
        self.val_split = str(stage3.auxiliary_classifier.selection_split)
        self.split_dir = Path(splits.paths.splits_root) / namespace
        self.images_dir = Path(stage1.paths.images_dir) / namespace

    def predict(self, records: list[dict]) -> np.ndarray:
        from scripts.utils.ham10000_classifier import predict_probabilities

        return predict_probabilities(self.model, records, self.resolution, device=self.device)

    def recorded_val_metrics(self) -> dict:
        return read_json(self.checkpoint_dir / "selection_metrics.json")

    def remeasured_val_metrics(self) -> dict:
        from scripts.utils.ham10000_classifier import records_from_split, true_class_indices

        records = records_from_split(pd.read_csv(self.split_dir / f"{self.val_split}.csv"), self.images_dir / self.val_split)
        return full_metric_suite(self.predict(records), true_class_indices(records))

    def describe(self) -> dict:
        return {"checkpoint_dir": str(self.checkpoint_dir), "val_split": self.val_split,
                "trained_on": self.manifest.get("data", {}).get("real_train_split"),
                "synthetic_images": self.manifest.get("data", {}).get("synthetic_images"), **self.identity}


def pilot_records(pilot: dict, image_ids: list[str]) -> list[dict]:
    """Classifier records for the standardised (512 letterboxed) candidates, in the given order."""
    records = []
    for image_id in image_ids:
        row = pilot["by_id"][image_id]
        records.append({"image_id": image_id, "image_path": str(row["image_path"]), "class_index": int(row["class_index"]), "dx": row["dx"]})
    return records


