def load_pilot(stage2_root: Path, namespace: str) -> dict:
    """One snapshot's pilot: manifest rows, the shared provenance, and its approval record."""
    pilot_dir = Path(stage2_root) / namespace / "pilot"
    manifest_path = pilot_dir / "generation_manifest.jsonl"
    approval_path = pilot_dir / "pilot_approval_manifest.json"
    if not manifest_path.is_file() or not approval_path.is_file():
        raise ComparisonRefused(f"no completed pilot under {pilot_dir} (need generation_manifest.jsonl and pilot_approval_manifest.json)")
    rows = [json.loads(line) for line in manifest_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    approval = read_json(approval_path)
    provenance = approval.get("split_provenance") or {}
    return {"root": str(stage2_root), "pilot_dir": str(pilot_dir), "rows": rows, "approval": approval, "provenance": provenance}


def lora_metadata(pilot: dict) -> dict:
    path = Path(str(pilot["provenance"].get("lora_weights_dir", ""))) / "metadata.json"
    return read_json(path) if path.is_file() else {}


