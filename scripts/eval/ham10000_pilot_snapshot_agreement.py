def parse_snapshots(values: list[str]) -> dict[str, Path]:
    snapshots: dict[str, Path] = {}
    for value in values:
        name, sep, root = value.partition("=")
        if not sep or not name or not root:
            raise SystemExit(f"--snapshot must be NAME=STAGE2_ROOT, got {value!r}")
        if name in snapshots:
            raise SystemExit(f"--snapshot {name} given twice")
        snapshots[name] = Path(root)
    return snapshots


def run(namespace: str, snapshot_roots: dict[str, Path], out_dir: Path, predictor, current_code_identity: str | None) -> dict:
    out_dir = Path(out_dir)
    if out_dir.exists() and any(out_dir.iterdir()):
        raise ComparisonRefused(f"{out_dir} is not empty; a re-run is a separate result — choose a new --out-dir")

    pilots = {name: load_pilot(root, namespace) for name, root in snapshot_roots.items()}
    checks = check_fairness(pilots, current_code_identity)
    snapshots = list(pilots)
    reproduction = check_classifier_reproduces_itself(predictor.recorded_val_metrics(), predictor.remeasured_val_metrics())
    checks["classifier_reproduces_its_recorded_classifier_val_metrics"] = reproduction
    checks["classifier"] = predictor.describe()

    order = {name: sorted(pilots[name]["by_id"]) for name in snapshots}
    probabilities = {name: predictor.predict(pilot_records(pilots[name], order[name])) for name in snapshots}
    predictions = prediction_table(pilots, probabilities, order)
    agreement = agreement_table(predictions, snapshots)
    per_recipe, pairs = paired_flips(predictions, snapshots)
    recall = recall_table(predictor.recorded_val_metrics())
    overlap_note = (f"The {checks['n_recipes']} pilot recipes are the first recipes of each class and are also part of the "
                    "full candidate set; they are kept in this comparison, not excluded.")

    out_dir.mkdir(parents=True, exist_ok=True)
    agreement.to_csv(out_dir / "snapshot_class_agreement.csv", index=False)
    agreement.pivot(index="snapshot", columns="class", values="mean_intended_probability").reindex(snapshots).to_csv(out_dir / "snapshot_class_mean_probability.csv")
    predictions.to_csv(out_dir / "per_image_predictions.csv", index=False)
    per_recipe.to_csv(out_dir / "paired_flips_per_recipe.csv", index=False)
    pairs.to_csv(out_dir / "paired_flips.csv", index=False)
    write_json(out_dir / "confusion_by_snapshot.json", confusion_by_snapshot(predictions, snapshots))
    write_json(out_dir / "classifier_val_recall.json", recall)
    write_json(out_dir / "fairness_check.json", checks)
    (out_dir / "report.md").write_text(render_report(agreement, recall, snapshots, checks, pairs, overlap_note), encoding="utf-8")
    build_review_sheet(pilots, predictions, snapshots, out_dir / "review_sheet.jpg")
    write_json(out_dir / "evaluation_manifest.json", {
        "namespace": namespace, "snapshots": {n: str(r) for n, r in snapshot_roots.items()},
        "cam_model_id": checks["classifier"].get("cam_model_id"), "code_identity_sha256": current_code_identity,
        "git_commit_hash": get_git_commit_hash(), "held_out_splits_read": False, "selection_rule_applied": None,
        "pilot_recipes_excluded": False, "created_at_utc": datetime.now(timezone.utc).isoformat(),
    })
    return {"agreement": agreement, "recall": recall, "checks": checks, "pairs": pairs, "out_dir": str(out_dir)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--namespace", required=True)
    parser.add_argument("--snapshot", action="append", required=True, help="NAME=STAGE2_ROOT, repeat once per snapshot (order is kept)")
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--device", default=None)
    args = parser.parse_args(argv)

    snapshot_roots = parse_snapshots(args.snapshot)
    predictor = AuxiliaryPredictor(args.namespace, device=args.device)
    result = run(args.namespace, snapshot_roots, args.out_dir, predictor, code_identity(Path(__file__).resolve().parents[2])["source_tree_sha256"])
    print((Path(result["out_dir"]) / "report.md").read_text(encoding="utf-8"))
    return 0


